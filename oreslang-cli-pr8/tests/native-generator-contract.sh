#!/usr/bin/env bash
# Requires Java/Graal Oreslang with stdlib PR #496, NOT a mocked runner.
set -euo pipefail
repo="$(cd -- "$(dirname -- "$0")/.." && pwd -P)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
cp -R "$repo/examples/hello-api" "$tmp/api"
cp -R "$repo/examples/hello-web" "$tmp/web"
cli="$repo/bin/oreslang-stack"
cp -R "$repo/examples/hello-api" "$tmp/manifest-collision"
mkdir -p "$tmp/manifest-collision/generated"
printf '{"schema":"foreign"}\n' > "$tmp/manifest-collision/generated/route-manifest.json"
if "$cli" generate --kind all --root "$tmp/manifest-collision"; then
  echo "foreign route manifest must fail before writing any adapters" >&2
  exit 1
fi
test ! -e "$tmp/manifest-collision/src/routes/rpc.ores"
test ! -e "$tmp/manifest-collision/src/routes/lambda.ores"
"$cli" generate --kind all --root "$tmp/api"
"$cli" generate --kind all --check --root "$tmp/api"
"$cli" check --root "$tmp/api"
"$cli" routes --root "$tmp/api" | grep -F '"kind":"route"'
grep -F 'route.greet(request)' "$tmp/api/src/routes/rpc.ores"
grep -F 'rpc.rpc_greet(request)' "$tmp/api/src/routes/lambda.ores"
grep -F 'oreslang.stack.inventory/v1' "$tmp/api/generated/route-manifest.json"
"$cli" build --root "$tmp/api"
test -s "$tmp/api/dist/oreslang-stack-source.tar.gz"
tar -tzf "$tmp/api/dist/oreslang-stack-source.tar.gz" | grep -F "bin/oreslang-stack-run"
tar -tzf "$tmp/api/dist/oreslang-stack-source.tar.gz" | grep -F "generated/route-manifest.json"
printf '\n// deliberately stale\n' >> "$tmp/api/src/routes/rpc.ores"
if "$cli" generate --kind all --check --root "$tmp/api"; then
  echo "stale generated file must fail verification" >&2
  exit 1
fi
"$cli" generate --kind all --root "$tmp/api"
printf 'hand authored\n' > "$tmp/api/src/routes/rpc.ores"
if "$cli" generate --kind all --root "$tmp/api"; then
  echo "hand-authored file must not be overwritten" >&2
  exit 1
fi
"$cli" generate --kind all --root "$tmp/web"
"$cli" generate --kind all --check --root "$tmp/web"
test -f "$tmp/web/src/pages/lambda.ores"
test ! -e "$tmp/web/src/pages/rpc.ores"
if "$cli" generate --kind rpc --root "$tmp/web"; then
  echo "web repositories do not generate RPC" >&2
  exit 1
fi
mkdir -p "$tmp/api/src/routes/users/[id]" "$tmp/api/src/routes/users/[name]"
for param in id name; do
  dir="$tmp/api/src/routes/users/[$param]"
  printf 'pub fnc show(String request) -> String { return request; }\n' > "$dir/handlers.ores"
  printf '// @ores-route GET /users/{%s} show\nimport module handlers from "./handlers";\npub fnc show(String request) -> String { return handlers.show(request); }\n' "$param" > "$dir/route.ores"
done
if "$cli" generate --kind all --root "$tmp/api"; then
  echo "ambiguous dynamic path shapes must fail" >&2
  exit 1
fi
if "$cli" deploy --root "$tmp/web" --target oreslang-stack; then
  echo "uncertified deploy must fail" >&2
  exit 1
fi
if "$cli" build --root "$tmp/web" --backend llvm; then
  echo "unsupported LLVM must fail" >&2
  exit 1
fi
# Additional adversarial source-tree, permission and idempotency coverage.
cp -R "$repo/examples/hello-api" "$tmp/inventory-only"
"$cli" routes --root "$tmp/inventory-only" | grep -F '"kind":"route"'
test ! -e "$tmp/inventory-only/src/routes/rpc.ores"
test ! -e "$tmp/inventory-only/src/routes/lambda.ores"
test ! -e "$tmp/inventory-only/generated"

cp -R "$repo/examples/hello-api" "$tmp/invalid-role"
printf '[repository]\nrole = "unsafe"\n' > "$tmp/invalid-role/oreslang-stack.toml"
if "$cli" generate --kind all --root "$tmp/invalid-role"; then
  echo "invalid repository roles must be rejected" >&2
  exit 1
fi
test ! -e "$tmp/invalid-role/src/routes/rpc.ores"

cp -R "$repo/examples/hello-api" "$tmp/duplicate-verb"
printf '\n// @ores-route GET / greet\n' >> "$tmp/duplicate-verb/src/routes/route.ores"
if "$cli" generate --kind all --root "$tmp/duplicate-verb"; then
  echo "duplicate route method must be rejected" >&2
  exit 1
fi
test ! -e "$tmp/duplicate-verb/src/routes/rpc.ores"

cp -R "$repo/examples/hello-api" "$tmp/symlink-attack"
mkdir -p "$tmp/outside"
ln -s "$tmp/outside" "$tmp/symlink-attack/src/routes/external"
if "$cli" generate --kind all --root "$tmp/symlink-attack"; then
  echo "symlinked route directory must be rejected" >&2
  exit 1
fi
test ! -e "$tmp/outside/rpc.ores"
test ! -e "$tmp/outside/lambda.ores"

cp -R "$repo/examples/hello-api" "$tmp/target-link"
ln -s "$tmp/outside/adapter.ores" "$tmp/target-link/src/routes/rpc.ores"
if "$cli" generate --kind all --root "$tmp/target-link"; then
  echo "symlinked generator target must be rejected" >&2
  exit 1
fi
test ! -e "$tmp/outside/adapter.ores"

cp -R "$repo/examples/hello-api" "$tmp/orphan-adapter"
mkdir -p "$tmp/orphan-adapter/src/routes/unused"
printf '// @generated by oreslang-stack-cli; DO NOT EDIT.\n' > "$tmp/orphan-adapter/src/routes/unused/rpc.ores"
if "$cli" generate --kind all --check --root "$tmp/orphan-adapter"; then
  echo "orphan adapter must fail read-only check" >&2
  exit 1
fi
"$cli" generate --kind all --root "$tmp/orphan-adapter"
test ! -e "$tmp/orphan-adapter/src/routes/unused/rpc.ores"
sha256sum "$tmp/orphan-adapter/src/routes/rpc.ores" "$tmp/orphan-adapter/src/routes/lambda.ores" "$tmp/orphan-adapter/generated/route-manifest.json" > "$tmp/before.sha"
"$cli" generate --kind all --root "$tmp/orphan-adapter"
sha256sum "$tmp/orphan-adapter/src/routes/rpc.ores" "$tmp/orphan-adapter/src/routes/lambda.ores" "$tmp/orphan-adapter/generated/route-manifest.json" > "$tmp/after.sha"
cmp "$tmp/before.sha" "$tmp/after.sha"

# Source-role and file-type guards run in the Oreslang guest, not the shell
# bootstrap. Every denial must happen during preflight before adapter writes.
expect_rejected() {
  local label="$1" diagnostic="$2" output
  shift 2
  if output="$("$cli" "$@" 2>&1)"; then
    echo "$label must be rejected" >&2
    exit 1
  fi
  if [[ "$output" != *"$diagnostic"* ]]; then
    echo "$label: missing expected diagnostic '$diagnostic': $output" >&2
    exit 1
  fi
}

cp -R "$repo/examples/hello-api" "$tmp/api-mixed-role"
printf '// @ores-page / render\n' > "$tmp/api-mixed-role/src/routes/page.ores"
expect_rejected "API route with page.ores" "source role mismatch" \
  generate --kind all --root "$tmp/api-mixed-role"
test ! -e "$tmp/api-mixed-role/src/routes/rpc.ores"
test ! -e "$tmp/api-mixed-role/src/routes/lambda.ores"
expect_rejected "read-only API inventory with page.ores" "source role mismatch" \
  routes --root "$tmp/api-mixed-role"
test ! -e "$tmp/api-mixed-role/generated"

cp -R "$repo/examples/hello-web" "$tmp/web-mixed-role"
printf '// @ores-route GET / show\n' > "$tmp/web-mixed-role/src/pages/route.ores"
expect_rejected "web page with route.ores" "source role mismatch" \
  generate --kind all --root "$tmp/web-mixed-role"
test ! -e "$tmp/web-mixed-role/src/pages/lambda.ores"

cp -R "$repo/examples/hello-api" "$tmp/api-nested-mixed-role"
mkdir -p "$tmp/api-nested-mixed-role/src/routes/nested"
printf '// @ores-page /nested render\n' > "$tmp/api-nested-mixed-role/src/routes/nested/page.ores"
expect_rejected "nested incompatible page" "source role mismatch" \
  generate --kind all --root "$tmp/api-nested-mixed-role"
test ! -e "$tmp/api-nested-mixed-role/src/routes/rpc.ores"

cp -R "$repo/examples/hello-api" "$tmp/leaf-is-directory"
mkdir "$tmp/leaf-is-directory/src/routes/route.ores.tmp"
mv "$tmp/leaf-is-directory/src/routes/route.ores" "$tmp/leaf-is-directory/src/routes/route.ores.tmp/original.ores"
mv "$tmp/leaf-is-directory/src/routes/route.ores.tmp" "$tmp/leaf-is-directory/src/routes/route.ores"
expect_rejected "route.ores as directory" "source leaf must be a file" \
  generate --kind all --root "$tmp/leaf-is-directory"
test ! -e "$tmp/leaf-is-directory/src/routes/rpc.ores"

cp -R "$repo/examples/hello-api" "$tmp/handlers-is-directory"
rm "$tmp/handlers-is-directory/src/routes/handlers.ores"
mkdir "$tmp/handlers-is-directory/src/routes/handlers.ores"
expect_rejected "handlers.ores as directory" "handlers.ores must be a file" \
  generate --kind all --root "$tmp/handlers-is-directory"
test ! -e "$tmp/handlers-is-directory/src/routes/rpc.ores"

cp -R "$repo/examples/hello-api" "$tmp/adapter-is-directory"
mkdir "$tmp/adapter-is-directory/src/routes/rpc.ores"
expect_rejected "rpc.ores as directory" "generated output must be a file" \
  generate --kind all --root "$tmp/adapter-is-directory"
test ! -e "$tmp/adapter-is-directory/src/routes/lambda.ores"

cp -R "$repo/examples/hello-api" "$tmp/manifest-is-directory"
mkdir -p "$tmp/manifest-is-directory/generated/route-manifest.json"
expect_rejected "manifest output as directory" "generated output must be a file" \
  generate --kind all --root "$tmp/manifest-is-directory"
test ! -e "$tmp/manifest-is-directory/src/routes/rpc.ores"

cp -R "$repo/examples/hello-api" "$tmp/role-is-directory"
rm "$tmp/role-is-directory/oreslang-stack.toml"
mkdir "$tmp/role-is-directory/oreslang-stack.toml"
expect_rejected "repository role manifest as directory" "project manifest must be a regular file" \
  generate --kind all --root "$tmp/role-is-directory"
test ! -e "$tmp/role-is-directory/src/routes/rpc.ores"

# A role cannot silently ignore the alternate top-level source tree.
cp -R "$repo/examples/hello-api" "$tmp/api-extra-pages"
mkdir -p "$tmp/api-extra-pages/src/pages"
expect_rejected "API with alternate pages source root" "source role mismatch" \
  generate --kind all --root "$tmp/api-extra-pages"
test ! -e "$tmp/api-extra-pages/src/routes/rpc.ores"
test ! -e "$tmp/api-extra-pages/generated"

cp -R "$repo/examples/hello-web" "$tmp/web-extra-routes"
mkdir -p "$tmp/web-extra-routes/src/routes"
expect_rejected "web with alternate routes source root" "source role mismatch" \
  routes --root "$tmp/web-extra-routes"
test ! -e "$tmp/web-extra-routes/generated"

cp -R "$repo/examples/hello-api" "$tmp/api-extra-root-link"
ln -s "$tmp/outside" "$tmp/api-extra-root-link/src/pages"
expect_rejected "API with linked alternate pages source root" "source role mismatch" \
  generate --kind all --root "$tmp/api-extra-root-link"
test ! -e "$tmp/api-extra-root-link/src/routes/rpc.ores"

cp -R "$repo/examples/hello-api" "$tmp/entry-is-directory"
rm "$tmp/entry-is-directory/src/main.ores"
mkdir "$tmp/entry-is-directory/src/main.ores"
expect_rejected "entrypoint as a directory" "entrypoint must be a regular file" \
  generate --kind all --root "$tmp/entry-is-directory"
test ! -e "$tmp/entry-is-directory/src/routes/rpc.ores"

echo "native Oreslang generator integration checks passed"
