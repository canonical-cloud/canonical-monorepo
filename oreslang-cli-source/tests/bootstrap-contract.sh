#!/usr/bin/env bash
# Host only: this mock NEVER establishes Oreslang compiler correctness.
set -euo pipefail
repo="$(cd -- "$(dirname -- "$0")/.." && pwd -P)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/project/src"
printf '[repository]\nrole = "api"\n' > "$tmp/project/oreslang-stack.toml"
printf 'pub routine main(): void { return; }\n' > "$tmp/project/src/main.ores"
cat > "$tmp/fake-oreslang" <<'EOS'
#!/usr/bin/env bash
set -euo pipefail
if [[ "$1" == "--check" ]]; then
  [[ -f "$2" ]] || exit 1
  [[ "${MOCK_COMPILER_REJECT:-}" != true ]] || exit 42
  exit 0
fi
if [[ "$1" == --allow-env=* ]]; then
  if [[ -n "${MOCK_GUEST_INVOCATION_FILE:-}" ]]; then
    printf 'invoked\n' > "$MOCK_GUEST_INVOCATION_FILE"
  fi
  if [[ "${MOCK_SPOOF_INIT:-}" == true && "$ORESLANG_STACK_COMMAND" == init ]]; then
    printf 'ORESLANG_STACK_ACTION_v1:initialized\n'
    exit 0
  fi
  if [[ "$ORESLANG_STACK_COMMAND" == "routes" || "$ORESLANG_STACK_COMMAND" == "check" ||
        ( "$ORESLANG_STACK_COMMAND" == "generate" && "$ORESLANG_STACK_CHECK" == "true" ) ]]; then
    for option in "$@"; do
      if [[ "$option" == --allow-write=* ]]; then
        echo "ERROR: read-only command was granted filesystem write access"
        exit 3
      fi
    done
  fi
  if [[ "$ORESLANG_STACK_BACKEND" != graal ]]; then
    echo 'ERROR: LLVM not supported'
    exit 0
  fi
  case "$ORESLANG_STACK_COMMAND" in
    init)
      if [[ -e "$ORESLANG_STACK_ROOT/oreslang-stack.toml" ||
            -e "$ORESLANG_STACK_ROOT/src" || -e "$ORESLANG_STACK_ROOT/generated" ]]; then
        printf 'ERROR: native init must refuse populated project\n'
      else
        mkdir -p "$ORESLANG_STACK_ROOT/src"
        printf '[repository]\nrole = "%s"\n' "$ORESLANG_STACK_ROLE" > "$ORESLANG_STACK_ROOT/oreslang-stack.toml"
        printf 'pub routine main(): void { return; }\n' > "$ORESLANG_STACK_ROOT/src/main.ores"
        if [[ "$ORESLANG_STACK_ROLE" == infra || "$ORESLANG_STACK_ROLE" == lambdas ]]; then
          printf '[candidate]\nrole = "%s"\ndeployable = false\n' "$ORESLANG_STACK_ROLE" > "$ORESLANG_STACK_ROOT/.oreslang-stack-$ORESLANG_STACK_ROLE.candidate.toml"
          if [[ "$ORESLANG_STACK_ROLE" == infra ]]; then
            mkdir -p "$ORESLANG_STACK_ROOT/src/infra"
            printf 'define module infra_candidate as\nend\n' > "$ORESLANG_STACK_ROOT/src/infra/config.ores"
          else
            mkdir -p "$ORESLANG_STACK_ROOT/src/functions/hello"
            printf 'define module handler as\nend\n' > "$ORESLANG_STACK_ROOT/src/functions/hello/handler.ores"
          fi
        else
          mkdir -p "$ORESLANG_STACK_ROOT/generated"
          printf '{"schema": "oreslang.stack.inventory/v1"}\n' > "$ORESLANG_STACK_ROOT/generated/route-manifest.json"
          if [[ "$ORESLANG_STACK_ROLE" == api || "$ORESLANG_STACK_ROLE" == admin-api ]]; then
            mkdir -p "$ORESLANG_STACK_ROOT/src/routes"
            for name in handlers route rpc lambda graphql; do
              printf 'define module test as\nend\n' > "$ORESLANG_STACK_ROOT/src/routes/$name.ores"
            done
            printf '// @generated by oreslang-stack-cli; DO NOT EDIT.\ntype Query { greet(request: String!): String! }\n' > "$ORESLANG_STACK_ROOT/src/routes/graphql.graphql"
          else
            mkdir -p "$ORESLANG_STACK_ROOT/src/pages"
            printf 'define module test as\nend\n' > "$ORESLANG_STACK_ROOT/src/pages/page.ores"
            printf 'define module test as\nend\n' > "$ORESLANG_STACK_ROOT/src/pages/lambda.ores"
          fi
        fi
        printf 'ORESLANG_STACK_ACTION_v1:initialized\n'
      fi ;;
    dev|build|check)
      mkdir -p "$ORESLANG_STACK_ROOT/generated"
      printf '{"schema": "oreslang.stack.inventory/v1"}\n' > "$ORESLANG_STACK_ROOT/generated/route-manifest.json"
      printf 'ORESLANG_STACK_ACTION_v1:%s\n' "$ORESLANG_STACK_COMMAND" ;;
    routes) printf 'ORESLANG_STACK_JSON_v1:{"schema":"oreslang.stack.inventory/v1"}\n' ;;
    generate) printf 'ORESLANG_STACK_ACTION_v1:generated\n' ;;
    deploy) printf 'ERROR: deployment denied\n' ;;
    *) printf 'ERROR: unrecognized\n' ;;
  esac
  exit 0
fi
printf 'app started\n'
EOS
chmod +x "$tmp/fake-oreslang"
export ORESLANG_BIN="$tmp/fake-oreslang"
test "$("$repo/bin/oreslang-stack" dev --root "$tmp/project")" = "app started"
"$repo/bin/oreslang-stack" build --root "$tmp/project" | grep -F 'NOT a compiled'
test -s "$tmp/project/dist/oreslang-stack-source.tar.gz"
tar -tzf "$tmp/project/dist/oreslang-stack-source.tar.gz" | grep -F "bin/oreslang-stack-run"
"$repo/bin/oreslang-stack" routes --root "$tmp/project" | grep -F '"schema"'
"$repo/bin/oreslang-stack" generate --kind all --root "$tmp/project" | grep -F 'generated'
"$repo/bin/oreslang-stack" generate --kind all --check --root "$tmp/project" | grep -F 'generated'
env ORESLANG_STACK_COMMAND=deploy "$repo/bin/oreslang-stack" routes --root "$tmp/project" | grep -F '"schema"'
"$repo/bin/oreslang-stack" check --root "$tmp/project" | grep -F 'verified'
tar -tzf "$tmp/project/dist/oreslang-stack-source.tar.gz" | grep -F 'src/main.ores'
tar -tzf "$tmp/project/dist/oreslang-stack-source.tar.gz" | grep -F '.oreslang-stack-entry'
printf 'do-not-include\n' > "$tmp/project/src/.env"
"$repo/bin/oreslang-stack" build --root "$tmp/project" >/dev/null
if tar -tzf "$tmp/project/dist/oreslang-stack-source.tar.gz" | grep -F '.env'; then
  echo "bundle must not contain .env secrets" >&2
  exit 1
fi
printf 'pub routine main(): void { return; }\n' > "$tmp/project/src/other.ores"
"$repo/bin/oreslang-stack" build --root "$tmp/project" --entry src/other.ores >/dev/null
tar -xzOf "$tmp/project/dist/oreslang-stack-source.tar.gz" ./.oreslang-stack-entry | grep -Fx 'src/other.ores'
rm -f "$tmp/project/dist/oreslang-stack-source.tar.gz"
mkdir "$tmp/project/dist/oreslang-stack-source.tar.gz"
if "$repo/bin/oreslang-stack" build --root "$tmp/project"; then
  echo "directory destination must be rejected" >&2
  exit 1
fi
if "$repo/bin/oreslang-stack" dev --root "$tmp/project" --entry src/../escape.ores; then
  echo "entrypath traversal must fail" >&2
  exit 1
fi
if "$repo/bin/oreslang-stack" deploy --root "$tmp/project" --target oreslang-stack; then
  echo "deploy must never succeed" >&2
  exit 1
fi
if "$repo/bin/oreslang-stack" dev --root "$tmp/project" --bad-flag; then
  echo "unknown flags must fail" >&2
  exit 1
fi
if "$repo/bin/oreslang-stack" build --backend llvm --root "$tmp/project"; then
  echo "llvm not admitted" >&2
  exit 1
fi
ln -s "$tmp/project" "$tmp/project-link"
if "$repo/bin/oreslang-stack" dev --root "$tmp/project-link"; then
  echo "symlink root must fail" >&2
  exit 1
fi

mkdir -p "$tmp/new-project"
printf 'preserve readme\n' > "$tmp/new-project/README.md"
"$repo/bin/oreslang-stack" init --role api --root "$tmp/new-project" | grep -F 'initialized Oreslang api project'
test -f "$tmp/new-project/oreslang-stack.toml"
test -f "$tmp/new-project/src/main.ores"
grep -F 'preserve readme' "$tmp/new-project/README.md"
if "$repo/bin/oreslang-stack" init --role api --root "$tmp/new-project"; then
  echo "init must refuse an already initialized project" >&2
  exit 1
fi
mkdir -p "$tmp/no-role"
if "$repo/bin/oreslang-stack" init --root "$tmp/no-role"; then
  echo "init without a role must fail" >&2
  exit 1
fi
mkdir -p "$tmp/bad-entry"
if "$repo/bin/oreslang-stack" init --root "$tmp/bad-entry" --role api --entry src/alternative.ores; then
  echo "init must reject a nondefault entrypoint before any writes" >&2
  exit 1
fi
test ! -e "$tmp/bad-entry/src"

mkdir -p "$tmp/bad-backend"
if "$repo/bin/oreslang-stack" init --root "$tmp/bad-backend" --role api --backend llvm; then
  echo "init must refuse unimplemented backends" >&2
  exit 1
fi
test ! -e "$tmp/bad-backend/src"


for role in infra lambdas; do
  mkdir -p "$tmp/$role-project"
  "$repo/bin/oreslang-stack" init --role "$role" --root "$tmp/$role-project" | grep -F "initialized Oreslang $role project"
  test -s "$tmp/$role-project/.oreslang-stack-$role.candidate.toml"
  test ! -e "$tmp/$role-project/generated/route-manifest.json"
done
mkdir -p "$tmp/occupied-candidate"
printf 'leave-alone\n' > "$tmp/occupied-candidate/.oreslang-stack-lambdas.candidate.toml"
if "$repo/bin/oreslang-stack" init --role lambdas --root "$tmp/occupied-candidate"; then
  echo 'init must refuse pre-existing candidate manifest' >&2
  exit 1
fi
test ! -e "$tmp/occupied-candidate/src"


# A forged or premature init receipt cannot certify a missing scaffold.
mkdir -p "$tmp/spoof-init"
if MOCK_SPOOF_INIT=true "$repo/bin/oreslang-stack" init --role api --root "$tmp/spoof-init"; then
  echo "init must reject success receipts with no files" >&2
  exit 1
fi
test ! -e "$tmp/spoof-init/src"

# Denied operations must not even invoke the guest (independent host gate).
for role in infra lambdas; do
  marker="$tmp/guest-$role-invoked"
  if MOCK_GUEST_INVOCATION_FILE="$marker" "$repo/bin/oreslang-stack" build --root "$tmp/$role-project"; then
    echo "$role build must fail before guest launch" >&2
    exit 1
  fi
  test ! -e "$marker"
done

# Check the actual init role, not just an Oreslang receipt.
mkdir -p "$tmp/role-mismatch"
if MOCK_SPOOF_INIT=true "$repo/bin/oreslang-stack" init --role lambdas --root "$tmp/role-mismatch"; then
  echo "init role mismatch must fail" >&2
  exit 1
fi


# Host role gate cannot depend on formatting of the TOML value.
mkdir -p "$tmp/space-role"
printf '[repository]\n  role= "infra"  \n' > "$tmp/space-role/oreslang-stack.toml"
mkdir -p "$tmp/space-role/src"
printf 'pub routine main(): void { return; }\n' > "$tmp/space-role/src/main.ores"
if MOCK_GUEST_INVOCATION_FILE="$tmp/spaces-guest" \
    "$repo/bin/oreslang-stack" build --root "$tmp/space-role"; then
  echo "candidate-only role must fail regardless of harmless TOML whitespace" >&2
  exit 1
fi
test ! -e "$tmp/spaces-guest"

# Generation success must not bypass actual compiler verification.
mkdir -p "$tmp/generate-compiler"
printf '[repository]\nrole = "api"\n' > "$tmp/generate-compiler/oreslang-stack.toml"
mkdir -p "$tmp/generate-compiler/src"
printf 'pub routine main(): void { return; }\n' > "$tmp/generate-compiler/src/main.ores"
if MOCK_COMPILER_REJECT=true "$repo/bin/oreslang-stack" generate --kind all --root "$tmp/generate-compiler"; then
  echo "generation must fail when compiler check rejects source" >&2
  exit 1
fi

# Permission strings are comma-delimited in the runtime. Reject roots with
# commas before guest launch rather than granting separate roots accidentally.
mkdir -p "$tmp/comma,root"
if MOCK_GUEST_INVOCATION_FILE="$tmp/comma-guest" "$repo/bin/oreslang-stack" init --role api --root "$tmp/comma,root"; then
  echo "comma-containing project root must fail closed" >&2
  exit 1
fi
test ! -e "$tmp/comma-guest"
test ! -e "$tmp/comma,root/src"

echo 'host bootstrap contract checks passed (mock interpreter; not native compilation)'
